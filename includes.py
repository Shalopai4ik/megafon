#!/usr/bin/env python3
"""
includes.py — ЕДИНАЯ ТАБЛИЦА: во что превращается строка счёта.
=============================================================================

Одно место, где решается ВСЁ, что зависит от названия услуги (pname):

    * в какую КОРЗИНУ попадает строка — из корзин складываются суммы
      «цена всего», «цена услуг» и «цена опций» в карточке абонента;
    * КТО ПЛАТИТ за неё по умолчанию — общество или человек;
    * к какой КАТЕГОРИИ потребления она относится (минуты / интернет / SMS) —
      по ним считаются пакеты, вердикты и подбор тарифа.

ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ. Раньше эти списки лежали в трёх модулях, а корзина
выбиралась лесенкой `if` с «всё остальное — перерасход» в конце. Из-за этого
международные звонки (не абонплата, не роуминг, не опция) молча падали в
«Перерасход пакета» и вешались на сотрудника — при нетронутом пакете 368
минут из 4000. Чтобы поправить одну услугу, приходилось лезть в логику.

Теперь правится ТОЛЬКО ЭТОТ ФАЙЛ, и правится строкой в таблице.

КАК ЧИТАЕТСЯ ТАБЛИЦА
--------------------
Правила проверяются СВЕРХУ ВНИЗ, побеждает первое подошедшее. Поэтому
частное стоит выше общего: «в международном роуминге» должно сработать
раньше, чем «международные вызовы».

Строка счёта подходит правилу, если её название содержит любую подстроку из
`names`. Если у правила заполнен ещё и `also`, то название обязано содержать
вдобавок любую подстроку оттуда (условие «И»).

Сравнение идёт по «сплющенному» названию: нижний регистр, схлопнутые
пробелы (см. domain.squash). Поэтому в таблице пишем строчными буквами и не
пытаемся угадать, сколько пробелов оператор поставил в этот раз.

ЧТО ЗНАЧАТ КОРЗИНЫ
------------------
    tariff   — абонентская плата: база тарифа и докупленные к ней пакеты;
    options  — опции и сервисы, не зависящие от выбора тарифа;
    overage  — связь, которую пакет не покрывает: перерасход пакета,
               межгород, международные звонки, спецномера;
    roaming  — связь вне домашнего региона; только на неё влияет командировка;
    skip     — служебные строки-итоги, деньгами не считаются вовсе.

КОРЗИН РОВНО ЧЕТЫРЕ (плюс `skip`), и это не случайность: в базе на каждую
заведена своя колонка `payer_*` в четырёх таблицах. Добавление пятой — это
миграция уже установленных контуров, поэтому услуга, которой нужен свой
плательщик, получает его полем `pays` прямо здесь, а не новой корзиной.

КТО ПЛАТИТ
----------
`pays` — это УМОЛЧАНИЕ, самый слабый уровень. Его перебивают, в порядке
возрастания силы: правило по услуге из настроек → командировка (только
роуминг) → пометки номера → цвет номера → ручной переключатель в карточке.
Подробности — в billing.PayerResolver.
"""

from __future__ import annotations

from typing import NamedTuple

COMPANY = "company"
EMPLOYEE = "employee"


class Include(NamedTuple):
    """Одно правило разнесения. Поля намеренно короткие — таблица читается глазами."""

    bucket: str                 # tariff | options | overage | roaming | skip
    pays: str                   # company | employee — умолчание, самое слабое
    names: tuple[str, ...]      # достаточно ЛЮБОЙ из этих подстрок
    why: str                    # что это за услуга; попадает в документацию
    also: tuple[str, ...] = ()  # если задано — название обязано содержать И это


# ═══════════════════════════════════════════════════════════════════════════
#  СЛУЖЕБНЫЕ СТРОКИ
#
#  «Итого начислено» — это СУММА строк, а не услуга. Посчитать её значит
#  удвоить счёт. Один раз уже стоило нам этого: в январской выгрузке
#  «Итого  начислено» с двумя пробелами не опозналось, легло обычной услугой,
#  и расход каждого из сорока абонентов удвоился.
# ═══════════════════════════════════════════════════════════════════════════

SKIP = Include(
    bucket="skip", pays=COMPANY,
    names=("итого начислено", "итого по услугам",
           "в том числе ндс", "в т.ч. ндс", "в т.ч ндс"),
    why="строка-итог, не услуга",
)


# ═══════════════════════════════════════════════════════════════════════════
#  ТАБЛИЦА. Сверху вниз, побеждает первое подошедшее правило.
# ═══════════════════════════════════════════════════════════════════════════

INCLUDES: tuple[Include, ...] = (

    SKIP,

    # ── Абонентская плата ────────────────────────────────────────────────
    Include(
        bucket="tariff", pays=COMPANY,
        names=("абонентская плата по тарифному плану",
               # Встречается и короткая формулировка — «Абонентская плата за
               # тариф (не облагается НДС)». Это та же база тарифа.
               "абонентская плата за тариф"),
        why="база тарифа",
    ),
    # ДОКУПЛЕННЫЙ ПАКЕТ ИНТЕРНЕТА — ТОЖЕ АБОНПЛАТА.
    # Оператор волен показать его как угодно: влить в абонплату одной суммой
    # либо выставить отдельной строкой «Абонентская плата за пакет
    # "Интернет 100"». Второй случай нельзя пропускать: не сложив такую
    # строку с абонплатой, получаем двойную ошибку — тариф опознаётся без
    # докупленного пакета (400 вместо 500), а сотня выглядит начислением ЗА
    # ИНТЕРНЕТ, то есть перерасходом. И система советует повысить тариф ровно
    # тому, кто уже доплатил за трафик.
    #
    # Условие из двух частей (names И also) нарочно: «Абонентская плата за
    # услугу Защита сотрудников» под него не попадает, «Мобильный интернет в
    # домашнем регионе» — тоже.
    Include(
        bucket="tariff", pays=COMPANY,
        names=("абонентская плата", "абонплата"),
        also=("интернет", "трафик", "передача данных"),
        why="докупленный пакет интернета — тоже абонплата",
    ),

    # ── Роуминг ──────────────────────────────────────────────────────────
    # ПРОВЕРЯЕТСЯ РАНЬШЕ ОПЦИЙ И МЕЖДУНАРОДНЫХ: только на роуминг влияет
    # командировка, и «вызовы в международном роуминге» обязаны опознаться
    # роумингом, а не международной связью.
    #
    # В списке только признаки НАХОЖДЕНИЯ В ДРУГОМ МЕСТЕ. Раньше здесь стояло
    # просто «международ», и под него попадала строка «Исходящие
    # МЕЖДУНАРОДНЫЕ вызовы В ДОМАШНЕМ РЕГИОНЕ» — звонок за границу со своего
    # города, никакой не роуминг. Ошибка была не косметической: такие звонки
    # списывались на компанию как «роуминг в командировке», хотя сотрудник
    # никуда не уезжал.
    Include(
        bucket="roaming", pays=EMPLOYEE,
        names=("роуминг", "путешеств", "страны пребывания",
               "региона пребывания", "за пределами домашнего региона"),
        why="связь вне домашнего региона",
    ),

    # ── Опции и сервисы ──────────────────────────────────────────────────
    # Не зависят от выбора тарифного плана, поэтому в сравнение тарифов их
    # стоимость не входит.
    Include(
        bucket="options", pays=COMPANY,
        names=("виртуальная атс", "ватс", "офис в кармане", "защита сотрудников",
               "ми.", "мобильное информирование", "детализация", "видеостриминг",
               "premium voice", "замена sim", "блокировка номера", "доставка счета",
               "дополнительный номер", "дополнительный городской номер",
               "автоответчик", "голосовая почта", "удержание вызова",
               "запрет развлекательного", "бизнес без границ", "экспресс-набор",
               "разовые услуги", "прочие начисления", "m2m"),
        why="опция или сервис, от тарифа не зависит",
    ),
    # ЛОВИМ ОПЦИИ, КОТОРЫХ НЕТ В СПИСКЕ ВЫШЕ.
    # «Абонентская плата за услугу …» — это подписка на опцию, как её ни
    # назови. Оператор придумывает новые услуги быстрее, чем мы их вносим, а
    # незнакомая падала в хвост таблицы и вешалась на сотрудника
    # «перерасходом» — хотя перерасходом абонплата не бывает по смыслу.
    #
    # Стоит НИЖЕ тарифных правил, поэтому «абонентская плата за услугу
    # Интернет 100» по-прежнему уходит в абонплату тарифа, а не сюда.
    Include(
        bucket="options", pays=COMPANY,
        names=("абонентская плата за услугу", "абонентская плата за опцию"),
        why="подписка на опцию под незнакомым названием",
    ),

    # ── Связь, которую пакет не покрывает ────────────────────────────────
    # ИЗ-ЗА ЭТОЙ СТРОКИ ВСЁ И ЗАТЕВАЛОСЬ.
    #
    # Международный и междугородный звонок пакетом НЕ ПОКРЫВАЕТСЯ вообще: он
    # тарифицируется отдельно, сколько бы минут в пакете ни оставалось.
    # Значит это и не перерасход пакета. Раньше такие строки падали в общий
    # «остаток» и по умолчанию вешались на сотрудника — при 368 использованных
    # минутах из 4000 человеку прилетало 229,50 ₽ «перерасхода».
    #
    # Платит общество: по договорённости с заказчиком на сотруднике только
    # перерасход, а межгород и международка со служебного номера — рабочие
    # звонки. Если нужно наоборот — поменяй `pays` в этой строке на EMPLOYEE,
    # больше менять нигде ничего не надо.
    Include(
        bucket="overage", pays=COMPANY,
        names=("международн", "междугородн"),
        why="межгород и международная связь: пакетом не покрывается",
    ),

    # ── Всё остальное ────────────────────────────────────────────────────
    # ЯВНЫЙ ХВОСТ, А НЕ МОЛЧАЛИВЫЙ `else`. Сюда попадает настоящий перерасход
    # пакета: минуты, гигабайты и SMS сверх включённого объёма. Он и есть та
    # часть счёта, которую по договорённости оплачивает сотрудник.
    #
    # Если в счёте завелась услуга, которой здесь не место, — заведи ей своё
    # правило ВЫШЕ этой строки. Что именно сюда попало, видно в карточке
    # абонента: «Из чего сложился счёт».
    Include(
        bucket="overage", pays=EMPLOYEE,
        names=(),                       # пустой список = подходит всему
        why="перерасход пакета: минуты, интернет и SMS сверх включённого",
    ),
)

# Хвост таблицы — он же ответ, когда не подошло ничего.
FALLBACK = INCLUDES[-1]


# ═══════════════════════════════════════════════════════════════════════════
#  КАТЕГОРИИ ПОТРЕБЛЕНИЯ
#
#  Отдельная от корзин ось: корзина отвечает на «кто платит», категория — на
#  «чего потратили». Одна и та же строка счёта имеет и то и другое: минуты
#  сверх пакета это категория `voice` и корзина `overage`.
# ═══════════════════════════════════════════════════════════════════════════

INTERNET_KW = ("интернет", "трафик", "передача данных", "gprs", "data")
SMS_KW = ("sms", "смс", "сообщени", "mms", "ммс")
VOICE_KW = ("вызов", "минут", "звон", "голос", "разговор", "телефон")

# Единицы измерения, по которым категория опознаётся даже при незнакомом
# названии: оператор регулярно придумывает новые формулировки, а «Мбайт»
# остаётся «Мбайт».
INTERNET_UNITS = ("мбайт", "гбайт", "кбайт", "байт")
VOICE_UNITS = ("мин",)

# Посуточное списание абонплаты: «Абонентская плата по тарифному плану
# (посуточное списание);31 шт;400,00». Объём здесь — дни, а не потребление.
DAILY_FEE_KW = ("посуточ",)


def match(service_squashed: str) -> Include:
    """Найти правило для НАЗВАНИЯ, уже пропущенного через domain.squash.

    Строку не «сплющиваем» здесь сами, чтобы не тянуть domain и не устраивать
    круговой импорт: includes ничего не знает о проекте, его читают все.
    """
    for inc in INCLUDES:
        if inc.names and not any(n in service_squashed for n in inc.names):
            continue
        if inc.also and not any(a in service_squashed for a in inc.also):
            continue
        return inc
    return FALLBACK


def bucket_of(service_squashed: str) -> str:
    """Корзина для названия услуги."""
    return match(service_squashed).bucket


def pays_by_default(service_squashed: str) -> str:
    """Кто платит за услугу, если не сработало ни одно правило посильнее."""
    return match(service_squashed).pays
