#  РАЗБОР СПИСКА КОМАНДИРОВОК
#
#  Формат взят из вашей выгрузки (komandirovki). Шапка занимает ДВЕ строки,
#  потому что часть заголовков объединена:
#
#      A                 B     C          D          E      F+G          H            I
#      Абонентский номер ФИО   период командировки   Страна Примечание   Утверждено   № СЗ
#                              начало     конец             Номер  Дата  (да/нет)
#      9111111111  Картофель Д.Г.  24.06.2023 01.07.2023 Китай 41111111 23.06.2023 да
#
#  Разбор НЕ привязан к номерам колонок: у разных выгрузок порядок и число
#  колонок отличаются. Поэтому:
#      * номер абонента ищем как первое поле из 10–11 цифр;
#      * две даты периода — первые две даты в строке;
#      * страна — первое текстовое поле после дат;
#      * «да/нет» — признак утверждения.
#  Так файл читается, даже если добавили или переставили колонку.
# ═══════════════════════════════════════════════════════════════════════════

# Дата периода. Разделитель любой из «.-/», год двух- или четырёхзначный:
# в одной выгрузке пишут 24.06.2023, в другой 24/06/23.
_TRIP_DATE = re.compile(r"\b(\d{1,2})[.\-/](\d{1,2})[.\-/](\d{2,4})\b")

# Та же дата, но уже в сортируемом виде: Excel часто отдаёт ГГГГ-ММ-ДД.
# Под _TRIP_DATE она не попадает: там первая группа не длиннее двух цифр.
_TRIP_DATE_ISO = re.compile(r"\b(\d{4})-(\d{1,2})-(\d{1,2})\b")

# Слова шапки — по ним строка распознаётся как заголовок и пропускается.
_TRIP_HEADER_KW = ("абонентский номер", "фио", "период командировки",
                   "страна", "утверждено", "примечание", "номер заказа")


def _iso_date(text: str) -> str:
    """Первая дата строки → ГГГГ-ММ-ДД. В базе даты хранятся так же."""
    found = _dates_in(text)
    return found[0] if found else ""


def _dates_in(text: str) -> list[str]:
    """ВСЕ даты текста в порядке появления, в формате ГГГГ-ММ-ДД.

    Нужен список, а не одна дата: период командировки бывает свёрнут в одну
    ячейку — «24.06.2023-01.07.2023» или «с 24.06.2023 по 01.07.2023». Пока
    отсюда возвращалась одна дата, у такой выгрузки конец периода терялся и
    командировка превращалась в однодневную.
    """
    s = str(text or "")
    out: list[tuple[int, str]] = []
    for m in _TRIP_DATE_ISO.finditer(s):
        year, month, day = m.groups()
        out.append((m.start(), f"{year}-{int(month):02d}-{int(day):02d}"))
    for m in _TRIP_DATE.finditer(s):
        day, month, year = m.groups()
        if len(year) == 2:
            # Двузначный год: 23 → 2023. Выгрузки командировок про прошлый век
            # не бывают, поэтому окно простое — всё в 2000-х.
            year = f"20{year}"
        if not (1 <= int(month) <= 12 and 1 <= int(day) <= 31):
            continue
        out.append((m.start(), f"{year}-{int(month):02d}-{int(day):02d}"))
    out.sort(key=lambda x: x[0])
    return [iso for _, iso in out]


def _ref_no(text: str) -> str:
    """Номер заказа или служебной записки — КАК В ФАЙЛЕ, а не «только цифры».

    Раньше здесь стояло re.sub(r"\\D", "", …), и номер терял всё, кроме цифр.
    На живых выгрузках это ломало оба поля:

        № СЗ  «АП-Ч.800-07/0035-2026» → «800070035 2026», номер-призрак;
                «б/н»                   → пустая строка, будто записки не было;
        заказ «ЛК»                    → пустая строка, а «ЛК» — нормальный
                                        номер заказа, просто буквами.

    Сверить командировку с бумагой по такому номеру нельзя. Убираем только
    служебный префикс «№» и лишние пробелы: в таблицу номер должен попадать
    в том же виде, в каком его написал человек.
    """
    out = " ".join(str(text).split())
    out = re.sub(r"^(?:№|N|No\.?)\s*", "", out)
    return out.strip(" -–—")


def _has_subscriber_number(line: str, delim: str) -> bool:
    """Есть ли в строке абонентский номер — поле из 10–11 цифр.

    По этому признаку кончается шапка. Без него разбор шапки съедал первую
    строку данных: у номера служебной записки «СЗ-12/345» в ячейке есть
    буквы «сз», строка опознавалась как второй ярус заголовка и целиком
    выбрасывалась вместе с командировкой.
    """
    cells = line.split(delim) if delim and delim in line else line.split()
    return any(10 <= len(re.sub(r"\D", "", raw)) <= 11 for raw in cells)


def _is_trip_header(line: str) -> bool:
    lo = " ".join(str(line).lower().replace("ё", "е").split())
    return sum(1 for kw in _TRIP_HEADER_KW if kw in lo) >= 2


# Заголовок → ключ колонки. Ищем вхождением, потому что подписи в разных
# выгрузках отличаются: «Утверждено (да/нет)», «Утверждено», «Согласовано».
_TRIP_COLUMNS = (
    ("number", ("абонентский номер", "номер телефона", "телефон")),
    ("username", ("фио", "сотрудник", "ф.и.о")),
    ("period", ("период командировки", "период", "дата начала", "начало")),
    ("country", ("страна",)),
    ("order_no", ("номер заказа", "заказ")),
    ("approved", ("утверждено", "согласовано")),
    ("memo_no", ("сз", "служебная записка")),
)

# Колонка «Дата» из блока «Примечание» — это дата ЗАЯВКИ, а не период.
# Сверка точным равенством, а не вхождением: «дата начала» тоже содержит
# «дата», и по вхождению эта колонка съедала начало периода.
_TRIP_ORDER_DATE_TITLES = ("дата", "дата заказа", "дата заявки", "дата сз")


def _trip_header_map(line: str, delim: str) -> dict[str, int]:
    """Сопоставить колонки файла с полями по тексту заголовка."""
    cells = [" ".join(c.strip().strip('"').lower().replace("ё", "е").split())
             for c in line.split(delim)]
    out: dict[str, int] = {}
    for idx, cell in enumerate(cells):
        if cell in _TRIP_ORDER_DATE_TITLES and "order_date" not in out:
            out["order_date"] = idx
    for key, aliases in _TRIP_COLUMNS:
        for idx, cell in enumerate(cells):
            if cell and any(a in cell for a in aliases) and key not in out:
                out[key] = idx
    return out


def parse_trips(text: str) -> dict[str, Any]:
    """Разобрать выгрузку командировок в строки для таблицы business_trips.

    Две стратегии, в порядке надёжности:

      1. ПО ЗАГОЛОВКУ. Если в файле есть строка «Абонентский номер | ФИО |
         … | Страна | … | Утверждено», берём значения из этих колонок.
      2. ПО СОДЕРЖИМОМУ. Заголовка нет — угадываем: номер это поле из 10–11
         цифр, период — первые две даты, страна — текстовое поле и т.д.

    ИСПРАВЛЕНО: сначала работала только вторая стратегия. Она разваливалась,
    если в ФИО есть цифры («Сотрудник 9596»): такое поле не считалось
    текстовым, именем становилась страна, а «№ СЗ» подхватывал цифры из
    фамилии. Теперь при наличии заголовка колонки берутся строго по нему.

    КОМАНДИРОВКА БЕЗ ПЕРИОДА — НЕ КОМАНДИРОВКА.
    Раньше строка без дат всё равно сохранялась, с пустыми date_start и
    date_end. А пустая дата в pick_trip означает «границы нет», то есть
    ВЕЧНУЮ командировку: номер считался командированным в любом месяце. Стоило
    один раз ошибиться файлом и загрузить сюда список сотрудников — и весь
    парк оказывался в командировке, а таблица командировок показывала всех
    подряд. Теперь строки без периода не сохраняются, а считаются отдельно
    (stats.no_dates), чтобы объяснить человеку, что за файл он принёс.
    """
    lines = [ln.rstrip() for ln in
             text.replace("\r\n", "\n").replace("\r", "\n").split("\n")]
    lines = [ln for ln in lines if ln.strip()]
    if not lines:
        return {"rows": [], "stats": {"rows": 0, "skipped": 0, "no_dates": 0}}

    delim = detect_delimiter(lines[:200])
    # Шапка ДВУХСТРОЧНАЯ: в первой строке «Примечание» на две колонки, во
    # второй — подписи «Номер заказа | Дата». Поэтому не выбираем одну лучшую
    # строку, а СКЛАДЫВАЕМ находки со всех строк шапки: первая найденная
    # колонка для каждого поля побеждает. Без этого «Номер заказа» терялся.
    #
    # ШАПКА БЫВАЕТ И СВЕРХУ. Колонка «№ СЗ» в выгрузке объединена по вертикали
    # на обе строки шапки, и её подпись физически лежит в ПЕРВОЙ строке — той
    # самой, где кроме неё только «Примечание». Два ключевых слова в такой
    # строке не набираются, заголовком она не считалась, и найденная в ней
    # колонка «№ СЗ» просто выбрасывалась: номер служебной записки приезжал
    # пустым у всех командировок. Поэтому находки строки НАД шапкой держим в
    # запасе (`above`) и подставляем те поля, которых в самой шапке не нашлось.
    columns: dict[str, int] = {}
    header_rows = 0
    above: dict[str, int] = {}
    above_at = -1
    # Номера строк, которые оказались шапкой. Нужны, чтобы верхняя строка
    # («;;;;;Примечание;;;№ СЗ») не попала потом в счётчик skipped: номера в
    # ней нет, и человек читал «пропущено строк без номера — 1» после каждой
    # успешной загрузки, гадая, что за строку у него не взяли.
    header_lines: set[int] = set()
    for i, line in enumerate(lines[:20]):
        if delim not in line:
            continue
        if _has_subscriber_number(line, delim):
            break  # пошли данные — шапка кончилась
        found = _trip_header_map(line, delim)
        if not found:
            above, above_at = {}, -1
            continue
        # Строка шапки — либо явная (два ключевых слова), либо строка
        # подзаголовков сразу под ней.
        if _is_trip_header(line) or header_rows:
            header_rows += 1
            # Порядок важен: сама шапка главнее строки над ней.
            for key, idx in list(found.items()) + list(above.items()):
                columns.setdefault(key, idx)
            header_lines.add(i)
            if above_at >= 0:
                header_lines.add(above_at)
            above, above_at = {}, -1
            if header_rows >= 2:
                break
        else:
            above, above_at = found, i

    rows: list[dict[str, Any]] = []
    skipped = 0
    no_dates = 0

    for i, line in enumerate(lines):
        if i in header_lines or _is_trip_header(line):
            continue

        # РАЗДЕЛИТЕЛЬ У КАЖДОЙ СТРОКИ СВОЙ.
        # Колонки из шапки — это номера полей, разрезанных ТЕМ ЖЕ символом.
        # Если строка разрезана пробелами (копипаст из Excel в блокнот), а
        # шапка была по «;», то индексы указывают в никуда: ФИО из трёх слов
        # даёт три поля вместо одного, и «Страна» уезжает на место фамилии.
        # Поэтому по шапке работаем только с теми строками, что разрезаны
        # тем же разделителем; остальные идут вторым путём, по содержимому.
        by_delim = bool(delim) and delim in line
        cells = [c.strip().strip('"') for c in line.split(delim)] if by_delim \
            else line.split()
        cols = columns if (by_delim and columns) else {}

        def cell(key: str, _cells: list[str] = cells,
                 _cols: dict[str, int] = cols) -> str:
            idx = _cols.get(key)
            return _cells[idx].strip() if idx is not None and idx < len(_cells) else ""

        # 1. Абонентский номер. Из колонки заголовка, иначе — первое поле
        #    из 10–11 цифр.
        #    ВНИМАНИЕ: переменная цикла названа `raw`, а не `cell` — иначе она
        #    затирала бы функцию cell() выше и разбор падал бы с
        #    «'str' object is not callable».
        number = ""
        by_header = cell("number")
        if by_header:
            digits = re.sub(r"\D", "", by_header)
            if 10 <= len(digits) <= 11:
                number = _normalize_number(digits)
        if not number:
            for raw in cells:
                digits = re.sub(r"\D", "", raw)
                if 10 <= len(digits) <= 11:
                    number = _normalize_number(digits)
                    break
        if not number:
            # В счётчик идут только строки, которые МОГЛИ быть командировкой.
            # Строка без единой цифры — это подпись, заголовок или пустая
            # рамка таблицы («;;;;;Примечание»), а не потерянный абонент.
            # Иначе после каждой удачной загрузки человек читал «пропущено
            # строк без номера — 1» и гадал, чего же у него не взяли.
            if any(ch.isdigit() for ch in line):
                skipped += 1
            continue

        # 2. ПЕРИОД. Дату заявки из блока «Примечание» в период не пускаем:
        #    когда её колонка опознана, она вычёркивается из кандидатов, а не
        #    надеемся на то, что она окажется третьей по порядку.
        order_date = _iso_date(cell("order_date"))
        order_date_idx = cols.get("order_date")
        period_cells = [c for i, c in enumerate(cells) if i != order_date_idx]

        dates: list[str] = []
        for c in period_cells:
            dates.extend(_dates_in(c))
        if not dates:
            # Номер есть, периода нет — это не командировка. Считаем отдельно:
            # такие строки означают, что принесли не тот файл.
            no_dates += 1
            continue
        if not order_date and len(dates) > 2:
            order_date = dates[2]
        date_start, date_end = dates[0], dates[1] if len(dates) > 1 else dates[0]
        if date_end < date_start:
            date_start, date_end = date_end, date_start

        # 3–6. Остальные поля. Если заголовок разобран — берём строго по нему;
        #      иначе угадываем по содержимому (см. докстроку функции).
        username = cell("username")
        country = cell("country")
        order_no = _ref_no(cell("order_no"))
        memo_no = _ref_no(cell("memo_no"))

        if "approved" in cols:
            approved = cell("approved").lower() in ("да", "yes", "+", "1")
        else:
            # Отдельная ячейка «да», а не подстрока: иначе «Данные» сойдёт за «да».
            approved = any(c.strip().lower() in ("да", "yes", "+", "1") for c in cells)

        if not cols:
            # ЗАПАСНОЙ ПУТЬ: колонок нет, идём по содержимому.
            #
            # Текстовые поля склеиваем ГРУППАМИ ИЗ СОСЕДНИХ. Причина: строка,
            # разрезанная пробелами, дробит ФИО на три поля, и «самое длинное
            # поле без цифр» — это одно слово, чаще всего отчество. Соседние
            # текстовые поля между цифрами — это одна ячейка исходной таблицы.
            groups: list[str] = []
            current: list[str] = []
            for c in cells:
                if c and not re.search(r"\d", c):
                    current.append(c)
                elif current:
                    groups.append(" ".join(current))
                    current = []
            if current:
                groups.append(" ".join(current))

            # Порядок колонок в таких выгрузках один: номер, ФИО, период,
            # страна. Поэтому берём по порядку, а не «самое длинное поле»:
            # длинное название страны иначе выигрывало у короткого ФИО.
            named = [g for g in groups if g.lower() not in ("да", "нет", "-", "—")]
            username = named[0] if named else ""
            country = named[1] if len(named) > 1 else ""
            for c in cells:
                digits = re.sub(r"\D", "", c)
                if not digits or digits == re.sub(r"\D", "", number) or _dates_in(c):
                    continue
                if len(digits) >= 6 and not order_no:
                    order_no = digits
                elif len(digits) <= 5 and not memo_no:
                    memo_no = digits

        rows.append({
            "number": number, "username": username,
            "date_start": date_start, "date_end": date_end,
            "country": country, "order_no": order_no,
            "order_date": order_date, "approved": approved,
            "memo_no": memo_no,
        })

    return {
        "rows": rows,
        "stats": {"rows": len(rows), "skipped": skipped, "no_dates": no_dates,
                  "approved": sum(1 for r in rows if r["approved"]),
                  "delimiter": delim},
    }


# ═══════════════════════════════════════════════════════════════════════════
#  ПРАВИЛА НОМЕРОВ СПИСКОМ: «номер : название правила»
#
#      Пришёл на делянку — а она вся размечена колышками,
#      Тут режь, тут не тронь, а вон там черемша не наша.
#      Ходить с бумажкой от куста к кусту — до вечера не управишься,
#      А делянка что вчера, что нынче: колышки те же самые.
#
#      Так перепиши разметку разом, одной тетрадкой,
#      И не тычь пальцем в каждый куст по второму кругу.
#      Только имена в тетрадке сверь со своими, а не со стороны:
#      Чужое имя на колышке — и вырубишь ты не то.
#
#  ЗАЧЕМ. Правило номера («Личный тариф», «Платит сам», «Руководство») до сих
#  пор вешалось мышью — по номеру за раз. А приходит оно списком: выгрузка из
#  кадров, письмо от бухгалтерии, старая таблица. На парке в полторы тысячи
#  номеров расставить их руками нельзя физически.
#
#  ФОРМАТ. Одна строка — одна пара «номер : название правила»:
#
#      9001234567: Личный тариф
#      +7 900 123-45-67; Платит сам
#      89001234567 | Руководство
#      9001234567    Личный тариф
#
#  Разделителем считается первый из «:;|», табуляция или два пробела подряд.
#  Одиночный пробел разделителем НЕ считается: названия правил из двух слов
#  («Личный тариф») иначе разрубались бы пополам.
#
#  ПРАВИЛО ИЩЕТСЯ ПО НАЗВАНИЮ, а не по коду: в тетрадке у человека написано
#  «Личный тариф», а не «personal». Названия сверяются схлопнуто — регистр,
#  двойные пробелы и «ё» не мешают. Код тоже принимается: если в файле уже
#  выгрузка из самой программы, она пишет коды.
#
#  ЧЕГО НЕ ДЕЛАЕМ. Не заводим правила, которых нет в справочнике. Новое
#  правило само по себе не значит ничего — пока у него не проставлены
#  плательщики, оно не двигает ни рубля, и молча созданная пустышка выглядела
#  бы как «загрузилось, а денег не изменило». Незнакомые названия возвращаем
#  списком: пусть человек заведёт их сам и загрузит список повторно.
# ═══════════════════════════════════════════════════════════════════════════

# Разделитель пары: «:», «;», «|», «,», табуляция или два пробела подряд.
_RULE_PAIR_SPLIT = re.compile(r"\s*[:;|]\s*|\t+|\s{2,}|\s*,\s*")


def parse_rule_links(text: str, rules: list[dict[str, Any]]) -> dict[str, Any]:
    """Разобрать список «номер : правило».

    Возвращает {'pairs': [(номер, код правила)], 'unknown': [...],
                'bad': [...], 'stats': {...}}.

        unknown — названия правил, которых нет в справочнике;
        bad     — строки, в которых не нашлось номера или названия.

    И то и другое возвращается НАРУЖУ, а не глотается: «загружено 40 из 300»
    без объяснения, где потерялись остальные, хуже, чем отказ целиком.
    """
    # Указатель «как это назвали» → код правила. Кладём и название, и код:
    # список приходит и от человека (названия), и из самой программы (коды).
    by_name: dict[str, str] = {}
    for rule in rules:
        by_name.setdefault(domain.squash(rule.get("label")), rule["code"])
        by_name.setdefault(domain.squash(rule.get("code")), rule["code"])

    pairs: list[tuple[str, str]] = []
    unknown: dict[str, int] = {}
    bad: list[str] = []
    seen: set[tuple[str, str]] = set()

    for raw in text.replace("\r\n", "\n").replace("\r", "\n").split("\n"):
        line = raw.strip().strip('"').strip()
        if not line or line.startswith("#"):
            continue

        chunks = [c.strip().strip('"').strip() for c in _RULE_PAIR_SPLIT.split(line)]
        chunks = [c for c in chunks if c]
        if len(chunks) < 2:
            bad.append(line)
            continue

        # Номер — первый кусок, в котором ровно 10–11 цифр. Правило — всё
        # остальное, склеенное обратно: в названии может быть и запятая
        # («Платит сам, взнос 490»), а она у нас разделитель.
        number, rest = "", []
        for chunk in chunks:
            digits = re.sub(r"\D", "", chunk)
            if not number and 10 <= len(digits) <= 11 and _is_mobile(
                    _normalize_number(digits)):
                number = _normalize_number(digits)
                continue
            rest.append(chunk)
        name = ", ".join(rest).strip()
        if not number or not name:
            bad.append(line)
            continue

        code = by_name.get(domain.squash(name))
        if not code:
            unknown[name] = unknown.get(name, 0) + 1
            continue
        if (number, code) not in seen:
            seen.add((number, code))
            pairs.append((number, code))

    return {
        "pairs": pairs,
        "unknown": [{"name": n, "count": c} for n, c in
                    sorted(unknown.items(), key=lambda kv: -kv[1])],
        "bad": bad[:20],          # длинный список битых строк никто не читает
        "stats": {"pairs": len(pairs), "numbers": len({n for n, _ in pairs}),
                  "unknown": sum(unknown.values()), "bad": len(bad)},
    }


def apply_roster(parsed: dict[str, Any]) -> dict[str, Any]:
    """Записать разобранный список в хранилище.

    Весь список пишется ОДНОЙ транзакцией. Дело не только в целостности:
    каждый выход в базу — это отдельный запуск psql, и на списке в двести
    строк поштучная запись превращается в минуты ожидания.
    """
    applied, with_limit, with_history = 0, 0, 0
    # Справочники материализуются ДО транзакции, а не внутри: заливка сама
    # читает базу после записи, а внутри блока команды ещё не отправлены.
    queries.ensure_reference_data()
    with db.transaction():
        for row in parsed["rows"]:
            queries.upsert_user(
                row["number"],
                username=row["username"],
                limit=row["limit"],
                position=row["position"],
                personnel_no=row["personnel_no"],
                note=row["note"],
                fetch=False,
            )
            applied += 1
            if 0 < row["limit"] < domain.LIMIT_SENTINEL:
                with_limit += 1
            if row["history"]:
                queries.set_roster_history(row["number"], row["history"])
                with_history += 1
    return {"applied": applied, "with_limit": with_limit,
            "with_history": with_history, "months": parsed["months"],
            "stats": parsed["stats"]}


def apply_bill(parsed: dict[str, Any]) -> dict[str, Any]:
    """Записать разобранный счёт в хранилище.

    Несколько счетов за разные месяцы накапливаются — так набирается реальная
    история. Повторная загрузка того же месяца перезаписывает его целиком.
    """
    saved = 0
    # СНАЧАЛА СПРАВОЧНИКИ, ПОТОМ ДАННЫЕ. Это и есть момент, когда база
    # перестаёт быть пустой: до первой загрузки в ней нет ни одной строки,
    # ни данных, ни справочников. Здесь ложатся оба разом — расчёт без
    # правил чипса и правил оплаты посчитал бы не то.
    #
    # Обязательно ДО транзакции: заливка справочников сама читает базу между
    # записями, а внутри db.transaction() команды только копятся в буфере и
    # своих же незакоммиченных строк не видят.
    queries.ensure_reference_data()

    # Весь счёт — одна транзакция: и целостнее, и на порядок быстрее, чем
    # отдельный поход в базу на каждого абонента.
    with db.transaction():
        for number, sub in parsed["subscribers"].items():
            if not sub["items"]:
                continue
            queries.save_report(
                number, sub["month"], sub["items"],
                report_date=sub["month"],
                plan_name=sub["plan_name"],
                total_charged=sub["total_charged"],
                vat=sub["vat"],
                # Сколько блоков счёта сложено в эту строку и почему их было
                # несколько. Признак живёт вместе со счётом: файл через месяц
                # никто не найдёт, а объяснять сумму придётся.
                parts=sub.get("parts", 1),
                parts_note=sub.get("parts_note", ""),
            )
            saved += 1

    # Реквизиты — уже ПОСЛЕ транзакции. Если в них не указан период,
    # set_invoice берёт последний загруженный, а увидеть его можно только
    # когда счёт уже лежит в базе.
    checksum = parsed.get("checksum") or {}
    if parsed["invoice"]:
        # Сверка ложится в реквизиты и живёт вместе со счётом. Иначе она
        # исчезала бы вместе с плашкой: обновил вкладку — и всё, счёт
        # по-прежнему не сходится, а сказать об этом уже некому.
        queries.set_invoice({**parsed["invoice"], "checksum": checksum})
    # Наружу она едет и отдельно: не сошлось — человек должен узнать об этом
    # ровно в тот момент, когда загрузил файл, а не когда по этим числам уже
    # сходил к руководителю.
    return {"saved": saved, "month": parsed["month"], "stats": parsed["stats"],
            "checksum": checksum}


# ═══════════════════════════════════════════════════════════════════════════
#  Сборка представлений (то, что уезжает на фронтенд)
# ═══════════════════════════════════════════════════════════════════════════

def _tariff_cost_of(bundle: dict[str, Any]) -> float:
    """Тарифозависимая часть счёта: абонплата + минуты/SMS/интернет.

    ИСПРАВЛЕНО: роуминг исключён — так же, как в domain.build_record.
    Иначе среднее по истории считалось бы по другой формуле, чем текущий
    месяц, и рекомендация опиралась бы на две несопоставимые величины.
    """
    total = 0.0
    for it in bundle["items"]:
        if domain.is_plan_fee(it["service"]):
            total += it["cost"]
        elif (it["cat"] in domain.CATEGORY_ORDER
              and not domain.is_addon(it["service"])
              and not domain.is_roaming(it["service"])):
            total += it["cost"]
    return total


def _averages(history: list[dict[str, Any]],
              bundles: list[dict[str, Any]]) -> tuple[float | None, float | None]:
    """Средний расход и средняя тарифозависимая часть по всей истории номера."""
    avg_total = (sum(h["total"] for h in history) / len(history)) if history else None
    avg_tariff = (sum(_tariff_cost_of(b) for b in bundles) / len(bundles)) if bundles else None
    return avg_total, avg_tariff


# Сколько строк начислений отдавать в списочном отчёте. Карточка показывает
# шесть крупнейших, полный список нужен только в модалке — она догружает его
# отдельным запросом (/api/subscriber/<номер>).
LIST_SERVICES = 8


def slim_for_list(record: dict[str, Any]) -> dict[str, Any]:
    """Убрать из записи то, чего списочный отчёт не показывает.

    ЗАЧЕМ. Отчёт на сотню номеров — это почти мегабайт JSON, и он целиком
    разбирается браузером до первой нарисованной карточки. На реальном счёте
    номеров под две тысячи. Всё, что здесь вычищается, либо не читается
    интерфейсом вовсе, либо доступно другим путём:

      * services  — полный список начислений. Карточке нужны шесть
        крупнейших, модалке — все, и она их догружает сама;
      * payment.buckets[].lines — построчная раскладка внутри корзины. Считать
        её надо (из неё получаются суммы «мы / сотрудник»), а показывать
        интерфейс её нигде не показывает;
      * recommendation.current — оценка ТЕКУЩЕГО тарифа по модели. Нужна была
        внутри расчёта, наружу не выводится;
      * названия и подписи тарифов в alternatives — они одни и те же у всех
        номеров, а каталог и так едет в отчёте отдельным полем. Браузер
        находит их по tariff_id.
    """
    services = record["services"]
    record["services_count"] = len(services)
    record["services"] = services[:LIST_SERVICES]

    payment = record.get("payment")
    if payment:
        for bucket in payment.get("buckets", ()):
            bucket.pop("lines", None)

    rec = record.get("recommendation")
    if rec:
        rec.pop("current", None)
        rec["alternatives"] = [
            {k: v for k, v in alt.items()
             if k not in ("tariff_name", "note", "kind", "over_min", "over_sms", "over_mb")}
            for alt in rec.get("alternatives", ())
        ]
    return record


def _build_one(number: str, bundle: dict[str, Any], *, data: dict[str, Any],
               catalog: list[dict[str, Any]],
               resolver: billing.PayerResolver) -> dict[str, Any]:
    """Собрать запись одного номера из уже прочитанного набора.

    Вынесено из тела цикла, чтобы тот же самый код мог пересчитать ОДИН номер
    после правки его настроек, не трогая остальные две тысячи. Логика обязана
    быть общей: разъедься она — карточка после правки показывала бы не то же,
    что показывает полный отчёт, и поймать это было бы нечем.
    """
    own_bundles = data["bundles"].get(number, [])
    history = queries.history_rows(own_bundles, data["roster"].get(number, {}))
    avg_total, avg_tariff = _averages(history, own_bundles)
    profile = queries.dataset_profile(data, number)

    # РАЗДЕЛЕНИЕ ОПЛАТЫ СЧИТАЕТСЯ ПЕРВЫМ, а запись собирается уже с
    # оглядкой на него. Порядок здесь принципиален: пока было наоборот,
    # рекомендация по тарифу успевала посчитаться и попасть в «потенциал
    # экономии» ДО того, как выяснялось, что за номер компания не платит.
    chip = data["chips"].get(number) or queries.blank_chip(number)
    trip = queries.pick_trip(data["trips"].get(number, []), bundle["month"])
    payment = billing.split_payment(
        bundle["items"], chip=chip, resolver=resolver,
        on_trip=bool(profile.get("on_trip")), trip=trip,
        # Лимит ловит правила с лимитами-признаками: у самоплатящих
        # номеров в этой колонке стоит не бюджет, а сумма взноса.
        limit=domain.to_float(profile.get("limit")),
    )

    record = domain.build_record(
        number, bundle["items"],
        month=bundle["month"],
        profile=profile,
        catalog=catalog,
        plan_name=bundle["plan_name"],
        total_charged=bundle["total_charged"],
        avg_total=avg_total,
        avg_tariff_cost=avg_tariff,
        company_pays=not (payment["excluded"] or payment["self_paid"]),
    )
    record["history"] = history
    record["category_history"] = queries.category_rows(own_bundles)
    record["trend"] = _trend_percent(record["history"], bundle["month"])
    record["chip"] = chip
    record["trip"] = trip
    record["payment"] = payment
    record["waste"] = billing.waste_of(record, payment)
    # Из каких прежних номеров склеена запись. Молчать об этом нельзя: человек
    # увидит расход вдвое больше привычного и решит, что программа врёт.
    record["merged_from"] = list(bundle.get("merged_from") or [])
    # Из скольких блоков ОДНОГО И ТОГО ЖЕ номера сложен счёт (перенос, смена
    # тарифа посреди периода). Это не то же, что merged_from: там сведены
    # РАЗНЫЕ номера одного человека, здесь — один номер, разбитый счётом надвое.
    record["bill_parts"] = int(bundle.get("parts") or 1)
    record["bill_parts_note"] = bundle.get("parts_note") or ""
    return record


def _month_context(month: str) -> tuple[dict[str, Any], list[dict[str, Any]],
                                        billing.PayerResolver, list[dict[str, Any]],
                                        list[dict[str, Any]]]:
    """Всё, что нужно сборке записей: набор данных, каталог, резолвер, правила.

    Справочники читаются ОДИН раз на отчёт. Если читать их внутри цикла, на
    сотне абонентов получится сотня лишних запросов к базе за одними и теми же
    строками.
    """
    catalog = domain.normalize_catalog(queries.get_tariffs())
    chip_rules = queries.get_chip_rules()
    resolver = billing.PayerResolver(
        rules=chip_rules,
        payment_rules=queries.get_payment_rules(only_enabled=True),
    )
    # ВСЁ ОСТАЛЬНОЕ — ТОЖЕ ОДНИМ НАБОРОМ ЗАПРОСОВ. История, потребление по
    # категориям, профили, командировки и чипсы читаются на весь парк сразу
    # (queries.month_dataset), а ниже разбираются по номерам уже в памяти.
    # Пока это делалось «по номеру», главный экран на сотне абонентов
    # открывался минутами: полторы тысячи обращений к базе на один отчёт.
    data = queries.month_dataset(month)
    # Счета расчётного месяца берём из того же набора: перечитывать их
    # отдельным запросом незачем, они уже прочитаны.
    month_bundles = sorted(
        (b for own in data["bundles"].values() for b in own if b["month"] == data["month"]),
        key=lambda b: b["number"])
    return data, month_bundles, resolver, chip_rules, catalog


def _finish_view(month: str, records: list[dict[str, Any]], *,
                 chip_rules: list[dict[str, Any]],
                 catalog: list[dict[str, Any]]) -> dict[str, Any]:
    """Досчитать по готовым записям всё, что считается «по всему парку сразу»."""
    # Индекс невыгодности считается по всему парку, поэтому только после того,
    # как собраны все записи.
    billing.assign_waste_index(records)
    records.sort(key=lambda r: (r["saving"], r["total"]), reverse=True)
    return {
        "month": month,
        "months": queries.months(),
        "subscribers": records,
        "summary": domain.build_summary(records),
        "payment_summary": billing.summarize(records),
        "tariff_stats": domain.build_tariff_stats(records),
        "trend": queries.trend(),
        # Реквизиты — ЗА ЭТОТ месяц, а не за последний загруженный. Иначе
        # шапка отчёта и суммы под ней приезжают из разных счетов.
        "invoice": queries.get_invoice(month),
        "tariffs": catalog,
        # Единый список правил (цвета + пометки) — интерфейс показывает их
        # одной группой, без искусственного деления. Прочитан выше, для
        # резолвера: второй раз ходить в базу за тем же незачем.
        "chip_rules": chip_rules,
        # Командировки идут вместе с отчётом, чтобы таблица на главной
        # рисовалась сразу, без отдельного запроса при каждой перерисовке.
        "trips": queries.get_trips(),
    }


def build_month_view(month: str) -> dict[str, Any]:
    """Полный отчёт месяца. Дорого: по записи на каждый номер парка."""
    with _view_lock:
        data, month_bundles, resolver, chip_rules, catalog = _month_context(month)
        # Чистка ПОСЛЕ всех расчётов: и индекс невыгодности, и сводки считаются
        # по полным записям, а урезанная запись нужна только для передачи.
        records = [slim_for_list(_build_one(b["number"], b, data=data, catalog=catalog,
                                            resolver=resolver))
                   for b in month_bundles]
        view = _finish_view(month, records, chip_rules=chip_rules, catalog=catalog)
        _cache_view(view)
        return view


# ═══════════════════════════════════════════════════════════════════════════
#  ПЕРЕСЧЁТ ПО МЕСТУ: НЕ ГОНЯТЬ ВЕСЬ ОТЧЁТ РАДИ ОДНОЙ ГАЛОЧКИ
#
#      Черемшу берут с корня, а не поле целиком,
#      Срезал стрелку — и полянка дальше зеленеет.
#      Дурень косит всё подряд да тащит впятером,
#      Умный вышел с ножиком — и к ужину поспеет.
#
#  БЫЛО. Любая правка — цвет чипса, галка «в командировке», лимит, правило —
#  вызывала build_month_view: перечитать всю базу, пересобрать записи на весь
#  парк, отдать браузеру полный отчёт. На боевой выгрузке это тридцать
#  мегабайт и двадцать секунд НА КАЖДОЕ НАЖАТИЕ. Человек снимал галочку и шёл
#  за чаем.
#
#  Обиднее всего, что менялось при этом обычно ОДНО ПОЛЕ У ОДНОГО НОМЕРА.
#
#  СТАЛО. Последний собранный отчёт лежит в памяти. Правка настроек одного
#  номера пересобирает ровно этот номер и подменяет его в готовом отчёте;
#  правка справочника пересобирает записи заново (тут никуда не деться —
#  правило может задеть кого угодно), но СЧЕТА при этом берутся из кэша
#  queries._bill_data, а не читаются из базы снова.
#
#  Наружу в обоих случаях уходит не отчёт, а РАЗНИЦА: записи, которые
#  действительно стали другими, плюс пересчитанные сводки. Обычно это один
#  номер и полкилобайта вместо тридцати мегабайт.
#
#  ПОЧЕМУ РАЗНИЦА, А НЕ ПРОСТО ПРАВЛЕНЫЕ НОМЕРА. Индекс невыгодности считается
#  по всему парку (90-й перцентиль), и правка одного номера способна сдвинуть
#  шкалу всем остальным. Такое случается редко, но если его не заметить, у
#  человека на экране останутся честные с виду, но устаревшие полоски.
#  Поэтому к правленым номерам добавляются те, у кого поехал индекс.
# ═══════════════════════════════════════════════════════════════════════════

_view_lock = threading.RLock()
_view_cached: dict[str, Any] | None = None

# Поля индекса невыгодности. Считаются по всему парку и меняются у номера, у
# которого сам по себе не изменилось ничего, — поэтому при сравнении «стало ли
# иначе» их выносят за скобки и досылают отдельной строчкой.
_INDEX_FIELDS = ("index", "reference")


def _differs_beyond_index(was: dict[str, Any] | None, now: dict[str, Any]) -> bool:
    """Изменилось ли в записи что-то, кроме индекса невыгодности."""
    if was is None:
        return True
    strip = lambda w: {k: v for k, v in (w or {}).items() if k not in _INDEX_FIELDS}
    if strip(was.get("waste")) != strip(now.get("waste")):
        return True
    return ({k: v for k, v in was.items() if k != "waste"}
            != {k: v for k, v in now.items() if k != "waste"})


def _cache_view(view: dict[str, Any]) -> None:
    global _view_cached
    _view_cached = view


def invalidate_view() -> None:
    """Забыть собранный отчёт: следующий запрос соберёт его заново.

    Звать там, где меняется что-то за пределами записей абонентов, — каталог
    тарифов, реквизиты, состав месяцев.
    """
    global _view_cached
    with _view_lock:
        _view_cached = None


def patch_month_view(month: str, numbers: set[str] | None = None) -> dict[str, Any]:
    """Пересчитать отчёт и вернуть РАЗНИЦУ, а не отчёт целиком.

    numbers — какие номера точно затронуты. None означает «затронуты могут
    быть любые» (правка справочника) и пересобирает все записи.

    Если готового отчёта в памяти нет — собираем полный и его же и отдаём:
    разницу не с чем считать, да и браузеру, который только что открылся,
    нужен весь отчёт.
    """
    with _view_lock:
        if _view_cached is None or _view_cached.get("month") != month:
            return build_month_view(month)

        records: list[dict[str, Any]] = _view_cached["subscribers"]

        # ДВА СЛЕПКА «КАК БЫЛО», и нужны оба — они ловят разное.
        #
        # previous держит ССЫЛКИ на прежние записи. Пересобранная запись — это
        # новый объект, и сравнение с прежним честно покажет, изменилось ли
        # хоть что-нибудь. Без этого правка справочника всегда объявляла бы
        # изменённым весь парк: пересобрали-то мы всех, а поменялись единицы.
        #
        # before_index держит ЧИСЛА. Записи, которые мы не пересобирали, в
        # списке те же самые объекты, и _finish_view правит им индекс
        # невыгодности прямо на месте — сравнивать объект с самим собой
        # бессмысленно. А индекс у них поехать может: он считается по 90-му
        # перцентилю всего парка, и один номер способен сдвинуть шкалу всем.
        previous = {r["number"]: r for r in records}
        before_index = {r["number"]: (r.get("waste") or {}).get("index")
                        for r in records}

        data, month_bundles, resolver, chip_rules, catalog = _month_context(month)

        # Состав парка изменился — номер появился или исчез. Разницей тут не
        # отделаться: в готовом отчёте остались бы лишние записи или не
        # хватало бы новых. Собираем заново, это честнее и всё равно редко.
        if len(month_bundles) != len(records):
            return build_month_view(month)

        wanted = [b for b in month_bundles
                  if numbers is None or str(b["number"]) in numbers]
        by_number = {r["number"]: i for i, r in enumerate(records)}
        for bundle in wanted:
            number = str(bundle["number"])
            position = by_number.get(number)
            if position is None:                  # номера нет в готовом отчёте
                return build_month_view(month)
            records[position] = slim_for_list(
                _build_one(number, bundle, data=data, catalog=catalog, resolver=resolver))

        view = _finish_view(month, records, chip_rules=chip_rules, catalog=catalog)
        _cache_view(view)

        changed: list[dict[str, Any]] = []
        shifted: list[dict[str, Any]] = []
        for record in view["subscribers"]:
            number = record["number"]
            was = previous.get(number)
            waste = record.get("waste") or {}
            if was is not record and _differs_beyond_index(was, record):
                changed.append(record)
            elif waste.get("index") != before_index.get(number):
                # У номера поехал ТОЛЬКО индекс невыгодности. Гнать ради
                # одного числа всю запись на семь килобайт — это ровно то
                # расточительство, от которого мы здесь и уходим.
                shifted.append({"number": number, "index": waste.get("index"),
                                "reference": waste.get("reference")})

        return {
            "month": view["month"],
            "partial": True,
            "subscribers": changed,
            "waste": shifted,
            # Сводки пересчитываются целиком всегда: они и так крошечные, а
            # считать «разницу» в KPI — способ рано или поздно разойтись с
            # тем, что показывает полный отчёт.
            "summary": view["summary"],
            "payment_summary": view["payment_summary"],
            "tariff_stats": view["tariff_stats"],
            "trips": view["trips"],
            "months": view["months"],
            "trend": view["trend"],
            # chip_rules НАМЕРЕННО НЕТ. Справочник правил — самая жирная часть
            # этого ответа, а меняет его ровно одна ручка /api/chip-rules,
            # которая и так возвращает его отдельным полем рядом с view.
            # Дублировать его в каждом ответе на каждую галочку — значит
            # возить шесть килобайт туда, где не поменялось ничего.
        }


def _trend_percent(history: list[dict[str, Any]], month: str) -> float:
    """Изменение расхода к предыдущему месяцу, в процентах."""
    idx = next((i for i, h in enumerate(history) if h["month"] == month), len(history) - 1)
    if idx <= 0:
        return 0.0
    prev = history[idx - 1]["total"]
    if prev <= 0:
        return 0.0
    return round((history[idx]["total"] - prev) / prev * 100, 1)


def build_subscriber_view(number: str, month: str | None = None) -> dict[str, Any]:
    catalog = domain.normalize_catalog(queries.get_tariffs())
    bundles = queries.bundles_for_number(number)
    if not bundles:
        return {}
    bundle = next((b for b in bundles if b["month"] == month), bundles[-1])
    history = queries.history_rows(bundles, queries.get_roster_history(number))
    avg_total, avg_tariff = _averages(history, bundles)
    record = domain.build_record(
        number, bundle["items"],
        month=bundle["month"],
        profile=queries.get_profile(number, bundle["month"]),
        catalog=catalog,
        plan_name=bundle["plan_name"],
        total_charged=bundle["total_charged"],
        avg_total=avg_total,
        avg_tariff_cost=avg_tariff,
    )
    record["history"] = history
    record["category_history"] = queries.category_rows(bundles)
    record["trend"] = _trend_percent(record["history"], bundle["month"])
    record["months"] = [b["month"] for b in bundles]
    # Тот же признак, что и в списочном отчёте (_build_one): счёт номера мог
    # быть сложен из нескольких блоков выгрузки. Поля обязаны совпадать —
    # разъедься они, карточка и список объясняли бы одну сумму по-разному.
    record["bill_parts"] = int(bundle.get("parts") or 1)
    record["bill_parts_note"] = bundle.get("parts_note") or ""
    return record


