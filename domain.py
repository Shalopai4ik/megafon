#
#  ПОЧЕМУ КАТАЛОГ СОБИРАЕТСЯ КОДОМ, А НЕ НАПИСАН СПИСКОМ.
#  Реальный набор — это КОМБИНАЦИИ: голосовая база × FMC × интернет-пакет.
#  Отсюда и суммы в счетах, которых нет ни в одной строке сетки: 186,95 —
#  это 16,95 + 140 + 30, а 726,95 — это 16,95 + 400 + 310. Пока в каталоге
#  лежали только девять «чистых» тарифов, номер с абонплатой 186,95 ₽
#  опознавался как «Пакет 140» (ближайшая цена), и дальше всё считалось от
#  неверного пакета.
#
#  Руками такую таблицу не пишут: 53 строки, и при правке ставки FMC
#  пришлось бы вычитать её из полусотни сумм. Поэтому части перечислены
#  один раз, а комбинации собираются `build_catalog()`.
#
#  Каталог редактируется в интерфейсе (Настройки → Тарифы) и приходит сюда
#  параметром, поэтому здесь он — только значение по умолчанию.
# ═══════════════════════════════════════════════════════════════════════════

# ───────────────────────────────────────────────────────────────────────────
#  ОТКУДА ЭТИ ЧИСЛА И ПОЧЕМУ ИХ НЕ НАДО «ПОПРАВЛЯТЬ» ПО ЛИСТУ ТАРИФОВ
#
#      Хозяин по книжке солил, а бочка возьми да прокисни;
#      сосед без книжки солил — и хрустит у него до весны.
#      Книжка пишет, как надо, а бочка — как вышло на деле,
#      и есть-то зимой не книжку, а то, что в бочке лежит.
#
#  Ставки списаны с листа «Тарифный план без абонентской платы —
#  ФЕДЕРАЛЬНЫЙ СПЕЦИАЛЬНЫЙ» (tarifs4.jpg). Там же сказано, что ежемесячная
#  абонентская плата по этому плану — 0,00, и единственная фиксированная
#  плата на нём — FMC, 16,95 ₽ за номер (см. FMC_FEE ниже). Других
#  абонплат на беспакетном тарифе не существует.
#
#  ГДЕ ЛИСТ РАСХОДИТСЯ СО СЧЁТОМ. Лист обещает 0,00 за исходящие на номера
#  сети Оператора и на номера корпоративного клиента, и 0,50 за междугородные.
#  В загруженных счетах это не так: оператор тарифицирует ВСЕ исходящие по
#  0,18, а межгород по 1,50. Проверено построчно на 9386653655 за 2026-06 —
#  начислено 311,76 ₽ при 1 035 мин «другим операторам» и 697 мин внутри
#  сети: 1 732 × 0,18, то есть по всем исходящим сразу.
#
#  РЕШЕНИЕ ЗАКАЗЧИКА: считаем по СЧЁТУ, а не по листу. Счёт — это то, что
#  реально списали, и модель обязана сходиться с ним, а не с обещанием.
#  Поэтому ставка одна на все исходящие, и разложение по направлениям здесь
#  сознательно НЕ сделано. Захочешь его вернуть — сначала возьми боевой
#  счёт и посмотри, как там разложены строки, иначе модель разъедется с
#  фактом и вся экономия поедет следом.
# ───────────────────────────────────────────────────────────────────────────

RATE_MIN = 0.18            # ₽ за минуту сверх пакета (другие операторы)
RATE_SMS = 0.05            # ₽ за SMS сверх пакета абонентам РФ
RATE_MB = 0.05             # ₽ за МБ сверх пакета

# Ставки ниже в расчёте НЕ участвуют: estimate_cost считает все исходящие по
# RATE_MIN, все SMS по RATE_SMS — см. решение выше. Оставлены как справка из
# того же листа, чтобы не искать бумажку заново, когда дойдут руки до
# разложения по направлениям.
RATE_MIN_INTERCITY = 0.50  # ₽ за минуту междугородного вызова по России
RATE_SMS_ABROAD = 1.00     # ₽ за SMS абонентам СНГ и других стран
RATE_MMS = 0.50            # ₽ за MMS абонентам РФ
RATE_MMS_ABROAD = 1.50     # ₽ за MMS абонентам СНГ и других стран

# FMC — городской номер, привязанный к мобильному. По листу это ЕДИНСТВЕННАЯ
# ежемесячная плата на «Федеральном Специальном». Пакетов не добавляет, но в
# сумме абонплаты счёта сидит и сдвигает её на 16,95 ₽. Без учёта этой
# добавки тариф из счёта не опознать.
FMC_FEE = 16.95

# Голосовые базы: код, название, абонплата, минуты, SMS, МБ.
VOICE_BASES: list[tuple[str, str, float, int, int, int]] = [
    ("fed", "Федеральный Специальный", 0.0, 0, 0, 0),
    ("140", "Пакет 140", 140.0, 700, 300, 15000),
    ("230", "Пакет 230", 230.0, 1500, 500, 25000),
    ("400", "Пакет 400", 400.0, 4000, 1000, 70000),
]

# Интернет-пакеты: код, название, цена, МБ, безлимит.
INTERNET_PACKS: list[tuple[str, str, float, int, bool]] = [
    ("30", "Интернет 30", 30.0, 1536, False),
    ("100", "Интернет 100", 100.0, 8192, False),
    ("220", "Интернет 220", 220.0, 15360, False),
    ("310", "Интернет 310", 310.0, 30720, False),
    ("400", "Интернет 400", 400.0, 0, True),
]


def _gb_text(mb: int) -> str:
    """«1,5 ГБ», «15 ГБ» — объём интернет-пакета как в тарифной сетке.

    Годится только для пакетов, которые в сетке и заданы гигабайтами: там МБ
    получены умножением на 1024 и делятся обратно нацело.
    """
    gb = mb / MB_IN_GB
    text = f"{gb:.1f}".rstrip("0").rstrip(".") if gb < 10 else f"{gb:.0f}"
    return text.replace(".", ",") + " ГБ"


def _mb_text(mb: int) -> str:
    """«15 000 МБ» — объём, включённый в голосовой пакет.

    Именно МБ, а не ГБ: в сетке эти пакеты записаны мегабайтами (15 000,
    25 000, 70 000), и перевод в гигабайты даёт 14,6 и 24,4 — числа, которых
    в счёте никто не увидит и которые только сбивают с толку.
    """
    return f"{mb:,}".replace(",", " ") + " МБ"


def _num_text(value: int) -> str:
    """1500 → «1 500». Неразрывный пробел, чтобы число не рвалось по строкам."""
    return f"{value:,}".replace(",", " ")


def build_catalog() -> list[dict[str, Any]]:
    """Собрать полный каталог: базы, интернет-тарифы и все их комбинации.

    ПОРЯДОК СТРОК ЗНАЧИМ. Разные наборы дают одинаковую абонплату:
    «Пакет 400» и «Федеральный Специальный + Интернет 400» — оба по 400 ₽,
    «Пакет 400 + FMC» и «Федеральный Специальный + FMC + Интернет 400» —
    оба по 416,95 ₽. Когда название в счёте не помогает выбрать, берётся
    первый подходящий по цене, поэтому простые наборы идут раньше составных
    (см. ключ сортировки в конце функции): более простое объяснение суммы
    вероятнее.
    """
    out: list[dict[str, Any]] = []

    def add(code: str, name: str, kind: str, fee: float, minutes: int, sms: int,
            internet_mb: int, unlimited: bool, note: str, parts: int) -> None:
        out.append({
            "id": code, "name": name, "kind": kind, "fee": round2(fee),
            "minutes": minutes, "sms": sms, "internet_mb": internet_mb,
            "unlimited_internet": unlimited,
            "rate_min": RATE_MIN, "rate_sms": RATE_SMS, "rate_mb": RATE_MB,
            "note": note, "_parts": parts,
        })

    # 1. Тарифы для модемов, планшетов и M2M: только интернет, без голоса.
    # Названы «Мобильный интернет», а не как пакет-добавка, потому что это
    # разные вещи с одинаковой ценой: тарифный план для модема против пакета,
    # докупленного к голосовому тарифу.
    for code, name, fee, mb, unlimited in INTERNET_PACKS:
        add(f"int_{code}", f"Мобильный интернет {code}", "internet", fee,
            0, 0, mb, unlimited,
            "Без ограничения объёма" if unlimited else _gb_text(mb), 1)

    # 2. Голосовые базы и всё, что на них навешивается.
    for base, base_name, base_fee, minutes, sms, base_mb in VOICE_BASES:
        for with_fmc in (False, True):
            for pack in [None, *INTERNET_PACKS]:
                code = base
                name = base_name
                fee = base_fee
                parts = 1
                mb = base_mb
                unlimited = False
                extra_note = ""

                if with_fmc:
                    code += "_fmc"
                    name += " + FMC"
                    fee += FMC_FEE
                    parts += 1

                if pack is not None:
                    pack_code, pack_name, pack_fee, pack_mb, pack_unlim = pack
                    code += f"_int{pack_code}"
                    name += f" + {pack_name}"
                    fee += pack_fee
                    parts += 1
                    # Докупленный пакет СКЛАДЫВАЕТСЯ с тем, что уже включено
                    # в тариф: оператор отдельным пакетом трафик не заменяет.
                    unlimited = pack_unlim
                    mb = 0 if pack_unlim else base_mb + pack_mb
                    extra_note = (" + безлимитный интернет" if pack_unlim
                                  else f" + {_gb_text(pack_mb)}")

                if base == "fed":
                    note = "Без абонплаты, всё по факту потребления"
                else:
                    note = (f"{_num_text(minutes)} мин · {_num_text(sms)} SMS"
                            f" · {_mb_text(base_mb)}")
                if with_fmc:
                    note += " · городской номер FMC"
                note += extra_note

                add(code, name, "voice", fee, minutes, sms, mb, unlimited,
                    note, parts)

    # Простое раньше составного, при равной сложности — дешёвое раньше, а при
    # равной цене — голосовое раньше модемного. Последнее не придирка: «Пакет
    # 400» и «Мобильный интернет 400» стоят одинаково, но обычных сотрудников
    # на порядок больше, чем модемов, и при выборе вслепую вероятнее первое.
    # Модем всё равно опознается по названию тарифа из счёта.
    out.sort(key=lambda t: (t["_parts"], t["fee"], t["kind"] != "voice"))
    for tariff in out:
        tariff.pop("_parts")
    return out


DEFAULT_TARIFFS: list[dict[str, Any]] = build_catalog()


def normalize_tariff(raw: dict[str, Any]) -> dict[str, Any]:
    """Привести пришедший с фронтенда тариф к полному набору полей."""
    return {
        "id": str(raw.get("id") or raw.get("name") or "tariff"),
        "name": str(raw.get("name") or raw.get("id") or "Без названия"),
        "kind": "internet" if str(raw.get("kind", "")).lower() == "internet" else "voice",
        "fee": max(0.0, to_float(raw.get("fee"))),
        "minutes": max(0, to_int(raw.get("minutes"))),
        "sms": max(0, to_int(raw.get("sms"))),
        "internet_mb": max(0, to_int(raw.get("internet_mb"))),
        "unlimited_internet": bool(raw.get("unlimited_internet")),
        "rate_min": to_float(raw.get("rate_min"), RATE_MIN),
        "rate_sms": to_float(raw.get("rate_sms"), RATE_SMS),
        "rate_mb": to_float(raw.get("rate_mb"), RATE_MB),
        "note": str(raw.get("note") or ""),
    }


def normalize_catalog(raw: Iterable[dict[str, Any]] | None) -> list[dict[str, Any]]:
    items = [normalize_tariff(t) for t in (raw or []) if isinstance(t, dict)]
    return items or [normalize_tariff(t) for t in DEFAULT_TARIFFS]


# ═══════════════════════════════════════════════════════════════════════════
#  Какой тариф у абонента
#
#  ПОЧЕМУ ГЛАВНЫЙ ПРИЗНАК — АБОНЕНТСКАЯ ПЛАТА, А НЕ НАЗВАНИЕ.
#  Название в счёте — маркетинговая подпись: «Федеральный Специальный B2B»,
#  «Управляй! Специалист +», суффиксы и даты версий оператор меняет когда
#  хочет. А списанная абонплата — твёрдый факт из того же счёта, и она прямо
#  показывает, из чего тариф собран: 186,95 ₽ — это 16,95 (FMC) + 140 (пакет)
#  + 30 (интернет). Поэтому сначала ищем по сумме, а названием уточняем.
# ═══════════════════════════════════════════════════════════════════════════

# Полный месяц и порог, ниже которого месяц считается неполным. 28 — потому
# что февраль; месяц из 28 дней полный, а вот 27 — уже обрезанный.
FULL_MONTH_DAYS = 30
FULL_MONTH_MIN_DAYS = 28

# Допуск при поиске тарифа по сумме, ₽. Взят из прежней версии подбора и
# закрывает мелочи, которых в каталоге нет: округления, разовые скидки,
# копеечные добавки вроде переадресации.
TARIFF_TOLERANCE = 15.0


def normalize_monthly_fee(daily_fee: float, days: int) -> float:
    """Посуточная абонплата за неполный месяц → сколько это было бы за месяц.

    Номер подключили пятнадцатого — оператор спишет половину абонплаты, и
    тариф за 400 ₽ в счёте будет выглядеть как тариф за 200 ₽. Прежде чем
    искать его в каталоге, сумму надо привести к полному месяцу.
    """
    fee = to_float(daily_fee)
    if fee <= 0:
        return 0.0
    if days <= 0 or days >= FULL_MONTH_MIN_DAYS:
        return round2(fee)
    return round2(fee / days * FULL_MONTH_DAYS)


def split_plan_fees(items: list[dict[str, Any]]) -> dict[str, Any]:
    """Разложить абонплату счёта на месячную, посуточную и число дней.

    Возвращает и то, что реально списано (`charged`), и приведённое к полному
    месяцу (`monthly`). Первое — факт для денег, второе — для поиска тарифа.
    """
    monthly_part = 0.0
    daily_part = 0.0
    days = 0
    for it in items:
        service = it.get("service") or ""
        if not is_plan_fee(service):
            continue
        cost = to_float(it.get("cost"))
        if is_daily_plan_fee(service):
            daily_part += cost
            # В объёме такой строки лежит число оплаченных дней («31 шт»).
            days = max(days, to_int(it.get("volume")))
        else:
            monthly_part += cost

    charged = round2(monthly_part + daily_part)
    monthly = round2(monthly_part + normalize_monthly_fee(daily_part, days))
    return {
        "charged": charged,
        "monthly": monthly,
        "monthly_part": round2(monthly_part),
        "daily_part": round2(daily_part),
        "days": days,
        # Неполный месяц: абонплата списана посуточно и дней меньше месяца.
        "partial": bool(daily_part > 0 and 0 < days < FULL_MONTH_MIN_DAYS),
    }


def _norm_name(text: str) -> str:
    return " ".join(str(text or "").lower().replace("ё", "е").split())


def match_tariff(plan_name: str, plan_fee: float,
                 catalog: list[dict[str, Any]]) -> dict[str, Any] | None:
    """Найти в каталоге тариф абонента. Возвращает копию с полем `matched_by`.

    `plan_fee` — абонплата ЗА ПОЛНЫЙ МЕСЯЦ (см. split_plan_fees), иначе номер
    с посуточным списанием опознается как тариф подешевле.

    Как ищем, в порядке убывания доверия:
        fee        — сумма совпала копейка в копейку;
        fee+name   — совпала сумма, и среди таких тариф нашёлся по названию;
        fee~       — сумма сошлась в пределах допуска (TARIFF_TOLERANCE);
        name       — сумма не сошлась, но название узнали;
        nearest    — не сошлось ничего, взяли ближайший по цене.

    Последние два случая — это уже догадка, и `matched_by` даёт интерфейсу
    возможность так и сказать, а не выдавать предположение за факт.
    """
    if not catalog:
        return None
    name = _norm_name(plan_name)
    fee = to_float(plan_fee)

    def by_name(pool: list[dict[str, Any]]) -> dict[str, Any] | None:
        if not name:
            return None
        for t in pool:
            if _norm_name(t["name"]) == name:
                return t
        for t in pool:
            tn = _norm_name(t["name"])
            if tn and (tn in name or name in tn):
                return t
        # ПО БАЗЕ ТАРИФА, без надстроек — но только когда среди кандидатов
        # НЕТ простого пакета с такой же ценой.
        #
        # Осторожность здесь выстрадана. Цена — главный признак, и 400 ₽ это
        # «Пакет 400»: 4 000 мин, 1 000 SMS, 70 000 МБ по тарифной сетке.
        # Сверка по базе названия сама по себе перебивала это и подсовывала
        # «Федеральный Специальный + Интернет 400» с нулевым пакетом минут —
        # потому что в счёте план подписан «Федеральный Специальный B2B».
        # Название плана оператор пишет одно на всю компанию, а что к нему
        # докуплено, видно только по абонплате.
        #
        # Поэтому база названия работает лишь там, где простого пакета за
        # такие деньги в сетке нет вовсе: 220 ₽ голосовым пакетом не бывает,
        # значит это интернет-пакет поверх основного тарифа.
        if not any(" + " not in t["name"] and t["kind"] == "voice" for t in pool):
            for t in pool:
                base = _norm_name(t["name"].split(" + ")[0])
                if base and (base in name or name in base):
                    return t
        return None

    def pick(pool: list[dict[str, Any]], kind: str) -> dict[str, Any]:
        # Каталог отсортирован «простое раньше составного», поэтому первый
        # подходящий — это самое простое объяснение суммы.
        hit = by_name(pool)
        return {**(hit or pool[0]), "matched_by": f"{kind}+name" if hit else kind}

    same_fee = [t for t in catalog if abs(t["fee"] - fee) <= 0.51]
    if same_fee:
        return pick(same_fee, "fee")

    near_fee = [t for t in catalog if abs(t["fee"] - fee) <= TARIFF_TOLERANCE]
    if near_fee:
        near_fee.sort(key=lambda t: abs(t["fee"] - fee))
        return pick(near_fee, "fee~")

    hit = by_name(catalog)
    if hit:
        # Название нашлось, но цена в счёте другая — доверяем счёту.
        return {**hit, "fee": round2(fee), "matched_by": "name"}

    nearest = min(catalog, key=lambda t: abs(t["fee"] - fee))
    return {**nearest, "fee": round2(fee), "matched_by": "nearest"}


def tariff_label(current: dict[str, Any] | None, plan_name: str = "") -> str:
    """Как называть тариф абонента в тексте рекомендации.

    ЗАЧЕМ ЭТО ОТДЕЛЬНАЯ ФУНКЦИЯ. Названий у тарифа фактически два, и они
    почти всегда разные:

      * ЧТО НАПИСАНО В СЧЁТЕ — «Федеральный Специальный B2B». Оператор пишет
        одну подпись на всю компанию, по ней не понять, что докуплено;
      * ЧТО ЭТО ПО КАТАЛОГУ — «Пакет 400 + Интернет 100». Опознаётся по
        абонплате (см. match_tariff), и только это годится для сравнения
        тарифов: пакеты минут и гигабайт есть лишь у каталожной записи.

    Пока рекомендация подставляла второе имя как есть, отчёт сам себе
    противоречил: в шапке карточки «Федеральный Специальный B2B», а строкой
    ниже «Пакет избыточен: тариф „Пакет 400 + Интернет 100“…». Человек искал
    у себя тариф, которого в счёте нет.

    Теперь в тексте стоит имя из счёта, а каталожное — рядом, с прямым
    указанием, откуда оно взялось.
    """
    if current is None:
        return "не определён по счёту"
    catalog_name = str(current.get("name") or "")
    plan = str(plan_name or "").strip()
    if not plan:
        return f"«{catalog_name}»"
    a, b = _norm_name(plan), _norm_name(catalog_name)
    if not b or a == b or a in b or b in a:
        return f"«{plan}»"
    return (f"«{plan}» (по абонплате {money_ru(current.get('fee') or 0)} "
            f"это «{catalog_name}»)")


# ═══════════════════════════════════════════════════════════════════════════
#  Стоимость потребления на конкретном тарифе
# ═══════════════════════════════════════════════════════════════════════════

def estimate_cost(tariff: dict[str, Any], usage: dict[str, float]) -> dict[str, Any]:
    """Во сколько обошёлся бы ЭТОТ месяц на ЭТОМ тарифе.

    Считаем только тарифозависимую часть: абонплата + перерасход по минутам,
    SMS и интернету. Опции (ВАТС, антифрод, роуминговые пакеты) не зависят от
    тарифа и в сравнение не входят — иначе тарифы сравнивались бы нечестно.
    """
    minutes = max(0.0, usage.get("voice_min", 0.0))
    sms = max(0.0, usage.get("sms_cnt", 0.0))
    mb = max(0.0, usage.get("internet_mb", 0.0))

    over_min = max(0.0, minutes - tariff["minutes"])
    over_sms = max(0.0, sms - tariff["sms"])
    over_mb = 0.0 if tariff["unlimited_internet"] else max(0.0, mb - tariff["internet_mb"])

    cost_min = over_min * tariff["rate_min"]
    cost_sms = over_sms * tariff["rate_sms"]
    cost_mb = over_mb * tariff["rate_mb"]
    total = tariff["fee"] + cost_min + cost_sms + cost_mb

    return {
        "tariff_id": tariff["id"],
        "tariff_name": tariff["name"],
        "kind": tariff["kind"],
        "fee": round2(tariff["fee"]),
        "total": round2(total),
        "over_min": round2(over_min),
        "over_sms": round2(over_sms),
        "over_mb": round2(over_mb),
        "cost_min": round2(cost_min),
        "cost_sms": round2(cost_sms),
        "cost_mb": round2(cost_mb),
        "overuse": sum(1 for x in (over_min, over_sms, over_mb) if x > 0),
        "note": tariff["note"],
    }


def _fits_internet_only(usage: dict[str, float],
                        current: dict[str, Any] | None = None) -> bool:
    """Модем ли это, которому можно предложить тариф без голоса вообще.

    ═══════════════════════════════════════════════════════════════════════
        Огурец на грядке лежит и молчит — так он тем и живёт, что молчит,
        а помидор молчит потому, что июль выдался хмурый.
        Оба зелёные, оба немые, с межи и не отличишь,
        да только один так задуман, а второй просто ждёт своего солнца.
    ═══════════════════════════════════════════════════════════════════════

    БЫЛО: голос ≤ 5 мин, SMS ≤ 5 шт, интернет > 0. В эту дырку идеально
    пролезал обычный сотрудник, который месяц просидел в отпуске: три минуты
    разговора, одна SMS, двадцать мегабайт фоновых обновлений. Подбор тут же
    выкидывал из каталога ВСЕ голосовые тарифы и советовал ему «Мобильный
    интернет 30» — тариф для модема, с которого позвонить физически нельзя.
    Экономия выходила 369 ₽ из 400, и вся она была враньём: человеку
    предлагали остаться без связи.

    СТАЛО, два условия вместо приблизительного «почти нет»:

      1. Голоса и SMS РОВНО ноль. Не «мало», а ни одной минуты и ни одного
         сообщения: модем не звонит никогда, а молчащий телефон молчит
         только этот месяц. Разница между «так задумано» и «так вышло» —
         это разница между нулём и тройкой, и мерить её порогом нельзя.

      2. Номер не сидит на ГОЛОСОВОМ тарифе. Если за него платят абонплату
         с пакетом минут — это телефон, кто бы что ни думал про его
         потребление. Тариф, оплаченный компанией, — свидетельство прямее
         любой эвристики.

    ПОЧЕМУ ЭТО НИЧЕГО НЕ СТОИТ. Настоящий модем от такой строгости не
    проигрывает ни рубля: «Мобильный интернет 220» и «Федеральный
    Специальный + Интернет 220» — это 220 ₽ и 15 ГБ в обоих случаях
    (см. build_catalog). Отказавшись от модемной ветки, мы теряем только
    название в карточке, а деньги остаются те же. Зато телефон больше
    никогда не получит совет пересесть на тариф без голоса.
    """
    if current is not None and current.get("kind") != "internet":
        return False
    return (usage.get("voice_min", 0.0) <= 0.0
            and usage.get("sms_cnt", 0.0) <= 0.0
            and usage.get("internet_mb", 0.0) > 0.0)


def _month_total_on(tariff: dict[str, Any], usage: dict[str, float]) -> float:
    """Во сколько встал бы месяц на этом тарифе. Только сумма, без разбора.

    Обрезанная версия estimate_cost: те же формулы, но ничего не округляется
    и не складывается в словарь. Нужна, чтобы отсортировать каталог, не
    собирая полный разбор по каждому тарифу.
    """
    over_min = max(0.0, max(0.0, usage.get("voice_min", 0.0)) - tariff["minutes"])
    over_sms = max(0.0, max(0.0, usage.get("sms_cnt", 0.0)) - tariff["sms"])
    over_mb = 0.0 if tariff["unlimited_internet"] else max(
        0.0, max(0.0, usage.get("internet_mb", 0.0)) - tariff["internet_mb"])
    return (tariff["fee"] + over_min * tariff["rate_min"]
            + over_sms * tariff["rate_sms"] + over_mb * tariff["rate_mb"])


# Сколько вариантов показываем в подборе тарифа. Больше пяти в карточку не
# помещается, а считать «на всякий случай» весь каталог — это и есть та
# работа, которую отчёт делал зря.
TARIFF_CHOICES = 5


# ═══════════════════════════════════════════════════════════════════════════
#  FMC В ПОДБОРЕ НЕ УЧАСТВУЕТ
#
#  FMC — это городской номер, привязанный к трубке. Пакетов он не добавляет,
#  стоит 16,95 ₽ и подключается по отдельному решению: человеку либо нужен
#  городской номер, либо не нужен. Предлагать «перейди на такой же тариф, но
#  с FMC» бессмысленно — это не про экономию, это про телефонию.
#
#  ПОЧЕМУ ИЗ КАТАЛОГА ОНИ НЕ УДАЛЕНЫ. Комбинации с FMC нужны, чтобы ОПОЗНАТЬ
#  тариф по абонплате: 186,95 ₽ — это 16,95 + 140 + 30. Выкинь их из каталога,
#  и такой номер опознается как «Пакет 140», а весь дальнейший расчёт поедет
#  от неверного пакета. Поэтому в каталоге они остаются, а фильтруется только
#  ПОДБОР.
#
#  Текущий тариф номера — исключение: если человек уже сидит на FMC, его
#  тариф в списке нужен, иначе не с чем сравнивать. Но как ВАРИАНТ ПЕРЕХОДА
#  FMC не предлагается никогда.
# ═══════════════════════════════════════════════════════════════════════════

def is_fmc(tariff: dict[str, Any]) -> bool:
    """Тариф содержит городской номер FMC.

    Смотрим и на код, и на название: код надёжен для каталога, собранного
    build_catalog, а название — единственное, за что можно зацепиться в
    строке, заведённой администратором руками.
    """
    return ("fmc" in str(tariff.get("id") or "").lower()
            or "fmc" in str(tariff.get("name") or "").lower())


def compare_tariffs(usage: dict[str, float], catalog: list[dict[str, Any]],
                    current_id: Any = None) -> list[dict[str, Any]]:
    """Оценка месяца на подходящих тарифах, от дешёвого к дорогому.

    ПОЧЕМУ НЕ ВЕСЬ КАТАЛОГ. Наружу уходит пятёрка лучших (alternatives) плюс
    оценка ТЕКУЩЕГО тарифа — остальное вызывающий код не смотрит. А каталог
    это полсотни комбинаций, и на каждую собирался словарь из тринадцати
    полей с семью округлениями: полсотни словарей на номер, из которых
    выживало шесть. На парке в две тысячи номеров — сто тысяч выброшенных
    словарей на каждую сборку отчёта.

    Теперь сортируем по дешёвой сумме (несколько умножений), а полный разбор
    собираем только для тех, кто кому-то нужен. Порядок и содержимое
    результата от этого не меняются.
    """
    # Текущий тариф ищем ДО выбора ветки каталога: он же и решает, телефон
    # это или модем. Раньше он доставался в самом низу, только чтобы попасть
    # в список сравнения, — и ветка выбиралась вслепую, по одному потреблению.
    current = (next((t for t in catalog if t["id"] == current_id), None)
               if current_id is not None else None)

    kind = "internet" if _fits_internet_only(usage, current) else "voice"
    candidates = [t for t in catalog if t["kind"] == kind] or catalog
    # Комбинации с FMC из подбора убираем — см. шапку раздела выше.
    candidates = [t for t in candidates if not is_fmc(t)] or candidates

    ranked = sorted(candidates, key=lambda t: (_month_total_on(t, usage), t["fee"]))
    keep = ranked[:TARIFF_CHOICES]
    if current is not None and current not in keep:
        # Текущий тариф нужен всегда, даже если он далеко не в лидерах: по
        # нему считается «сколько платим сейчас».
        keep.append(current)

    estimates = [estimate_cost(t, usage) for t in keep]
    estimates.sort(key=lambda e: (e["total"], e["fee"]))
    return estimates


# Порог «живой SIM-карты». Несколько минут, пара сообщений и десятки
# мегабайт набегают сами: оповещения оператора, обновление часов, служебный
# трафик. Такой номер не работает, за него просто платят.
IDLE_VOICE_MIN = 5.0
IDLE_SMS_CNT = 5.0
IDLE_INTERNET_MB = 50.0


def cat_word(label: str) -> str:
    """Название категории внутри фразы: «Минуты» → «минуты», «SMS» → «SMS».

    Без этого в перечислении получалось «sms — 109 шт»: аббревиатуру ломать
    нельзя, а обычное слово посреди предложения с большой буквы выглядит так
    же неряшливо.
    """
    return label if label.isupper() else label.lower()


def usage_level(usage: dict[str, float]) -> str:
    """Насколько номер вообще использовался: none / idle / normal.

    Считается по ИСХОДЯЩЕМУ потреблению: входящие звонки и SMS бесплатны и
    ничего не говорят о том, нужен ли номер.

    Три уровня, потому что говорить о них надо по-разному: «none» — за месяц
    ноль, тут решение отключать или менять тариф на минимальный; «idle» —
    единицы минут, то есть служебный трафик; «normal» — обычный разбор.
    """
    voice = usage.get("voice_min", 0.0)
    sms = usage.get("sms_cnt", 0.0)
    mb = usage.get("internet_mb", 0.0)
    if voice <= 0 and sms <= 0 and mb <= 0:
        return "none"
    if voice < IDLE_VOICE_MIN and sms < IDLE_SMS_CNT and mb < IDLE_INTERNET_MB:
        return "idle"
    return "normal"


