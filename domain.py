# СПИСКИ НАЗВАНИЙ ЖИВУТ В includes.py — ТАМ ОНИ ВСЕ И ПРАВЯТСЯ.
#
# Раньше они лежали здесь, и чтобы понять, почему услуга попала не туда,
# приходилось читать три модуля сразу: списки в domain, лесенку корзин в
# billing, умолчания плательщика там же. Теперь это одна таблица, и она же
# отвечает на вопрос «кто за это платит».
INTERNET_KW = includes.INTERNET_KW
SMS_KW = includes.SMS_KW
VOICE_KW = includes.VOICE_KW
DAILY_FEE_KW = includes.DAILY_FEE_KW


def normalize_number(value: Any) -> str:
    """Привести абонентский номер к десяти цифрам: без +7, восьмёрки и скобок.

    ОДНО ПРАВИЛО НА ВСЮ ПРОГРАММУ. Номер приходит из трёх мест — из счёта, из
    списка работников и из поля ввода в настройках, — и записан везде
    по-своему: «+7 912 345-67-89», «89123456789», «9123456789». Сравнивать их
    «как есть» нельзя: тот же человек окажется тремя разными абонентами.

    Раньше это правило жило внутри разборщика счёта (server._normalize_number)
    и больше нигде — а значит, номер, введённый руками, с номером из счёта не
    совпадал.
    """
    digits = re.sub(r"\D", "", str(value or ""))
    if len(digits) == 11 and digits[0] in "78":
        digits = digits[1:]
    return digits[-10:] if len(digits) > 10 else digits


def squash(text: Any) -> str:
    """Привести название услуги к виду, по которому можно искать подстроку.

    ЗАЧЕМ. Названия в счёте приходят из PDF, и пробелы там какие угодно:
    «Итого  начислено» с двумя пробелами, неразрывные пробелы вместо
    обычных, переносы строк внутри названия. Сравнение «как есть» на таком
    ломается молча — и это уже стоило нам денег: в выгрузке за январь строка
    «Итого  начислено» не опозналась как итоговая, не отфильтровалась и
    легла в расходы обычной услугой. Расход каждого из сорока абонентов
    удвоился.

    `str.split()` режет по любому пробельному символу, включая неразрывный,
    поэтому склейка через него чинит все три случая разом. Заодно приводим
    «ё» к «е»: в счетах встречается и так, и так.
    """
    return " ".join(str(text or "").lower().replace("ё", "е").split())


@functools.lru_cache(maxsize=8192)
def include_of(service: str) -> includes.Include:
    """Правило из includes.INCLUDES, под которое подошла строка счёта.

    Единственная точка, где название услуги превращается в решение. Всё
    остальное (корзина, плательщик, «это абонплата?») — производные от неё,
    поэтому разъехаться они не могут.

    ПОЧЕМУ С КЭШЕМ. Названий услуг в счёте несколько десятков, а строк —
    десятки тысяч, и каждая спрашивает про свою корзину по четыре раза
    (is_plan_fee, is_roaming, is_addon, bucket_of). Без кэша это сорок тысяч
    проходов по таблице с поиском подстрок — почти половина времени сборки
    отчёта. С кэшем таблица честно просматривается по разу на КАЖДОЕ
    РАЗЛИЧНОЕ название, дальше берётся готовый ответ.

    Таблица правится в исходниках, на ходу не меняется, поэтому кэш не
    протухает. Если когда-нибудь понадобится менять её из интерфейса —
    сбрасывать через include_of.cache_clear().
    """
    return includes.match(squash(service))


def is_meta(service: str) -> bool:
    """Служебная строка-итог, которую нельзя суммировать в расход."""
    return include_of(service).bucket == "skip"


def is_plan_fee(service: str) -> bool:
    """Абонплата: база тарифа или докупленный к нему пакет интернета."""
    return include_of(service).bucket == "tariff"


def is_daily_plan_fee(service: str) -> bool:
    """Абонплата списана посуточно, а не за месяц целиком."""
    s = squash(service)
    return is_plan_fee(s) and any(k in s for k in DAILY_FEE_KW)


def is_addon(service: str) -> bool:
    """Опция/сервис, не зависящий от тарифного плана."""
    return include_of(service).bucket == "options"


@functools.lru_cache(maxsize=4096)
def is_outgoing(service: str) -> bool:
    """Исходящая ли услуга. Входящие вызовы и SMS пакет не расходуют.

    Кэш по той же причине, что и у include_of: названий несколько десятков,
    а строк счёта — десятки тысяч.
    """
    s = squash(service)
    if "входящ" in s:
        return False
    return True


def is_roaming(service: str) -> bool:
    """Связь вне домашнего региона (роуминг), а не просто «международная».

    Признаки — в includes.INCLUDES, правило с корзиной `roaming`. Там же
    объяснено, почему «международные вызовы в домашнем регионе» роумингом
    НЕ считаются.
    """
    return include_of(service).bucket == "roaming"


@functools.lru_cache(maxsize=8192)
def categorize(service: str, category: str = "", service_type: str = "", unit: str = "") -> str:
    """Отнести услугу к корзине voice / internet / sms / other.

    Кэшируется: разных сочетаний «название + единица» в счёте несколько
    десятков, а зовут её на каждую строку.
    """
    text = squash(" ".join(x for x in (service, category, service_type) if x))
    if is_plan_fee(text) or is_meta(text):
        return "other"
    if any(k in text for k in INTERNET_KW) or unit in ("мбайт", "гбайт", "кбайт", "байт"):
        return "internet"
    if any(k in text for k in SMS_KW):
        return "sms"
    if any(k in text for k in VOICE_KW) or unit == "мин":
        return "voice"
    return "other"


# ═══════════════════════════════════════════════════════════════════════════
#  ЛИМИТЫ-ПРИЗНАКИ: правило навешивается на номер САМО
#
#  ЗАЧЕМ. Есть номера, за которые компания не платит вовсе: человек вносит за
#  себя сам. Отличить их можно по лимиту из списка работников — там стоит не
#  бюджет на связь, а сумма взноса (490, 90, 690, 1070). Отмечать такие номера
#  руками — это сотня одинаковых движений мышью и гарантированные пропуски.
#
#  Поэтому у ЛЮБОГО правила номера есть поле match_limits. Совпал лимит с
#  одним из чисел — правило действует так же, как если бы его навесили
#  вручную: тот же цвет, те же эффекты на деньги. Механизм общий, поэтому
#  завтра «ловить по лимиту» можно будет что угодно ещё — модемы, безлимит,
#  подрядчиков, — и кода это не коснётся.
#
#  СВЕРКА КОПЕЙКА В КОПЕЙКУ. Лимит приходит из выгрузки списка работников, а
#  не из счёта: округлениям и посуточным списаниям взяться неоткуда. Допуск
#  здесь только размывал бы границу между 490 и соседними суммами.
# ═══════════════════════════════════════════════════════════════════════════

def parse_match_limits(text: Any) -> list[float]:
    """«490, 90; 690 1070» → [490.0, 90.0, 690.0, 1070.0].

    Разделитель любой: запятая, точка с запятой, пробел, перевод строки —
    человек в поле настроек напишет как ему удобнее, и спорить с ним из-за
    лишней запятой мы не будем. Мусор молча отбрасывается, ноль и
    отрицательные тоже: лимит 0 стоит у половины парка и означает «не задан»,
    ловить по нему — значит поймать всех разом.
    """
    out: list[float] = []
    for piece in re.split(r"[^0-9.,]+", str(text or "")):
        # Внутри куска запятая — это десятичный разделитель («490,50»);
        # разделителем списка она быть уже не может, её съел split.
        value = to_float(piece.replace(",", "."))
        if value > 0 and value not in out:
            out.append(value)
    return out


def limits_text(limits: Iterable[float]) -> str:
    """[490.0, 90.5] → «490, 90.5». Целые суммы без хвоста «.0»."""
    return ", ".join(str(int(v)) if float(v).is_integer() else str(v)
                     for v in limits)


def rules_by_limit(rules: Iterable[dict[str, Any]]) -> dict[float, list[str]]:
    """{лимит: [коды правил]} — по этой таблице номер получает свои правила.

    Собирается один раз на отчёт: перебирать список правил на каждый из двух
    тысяч номеров незачем, а разных лимитов всего несколько.
    """
    index: dict[float, list[str]] = {}
    for rule in rules:
        for limit in parse_match_limits(rule.get("match_limits")):
            index.setdefault(limit, []).append(str(rule["code"]))
    return index


